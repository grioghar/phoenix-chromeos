#!/usr/bin/env python3
"""Generate Phoenix machine profiles (profiles/<vendor>/<model>.conf) from research/*.json.

The path must match what detect/phoenix-detect.sh looks up:
  vendor = slug of the first word of DMI sys_vendor ("Dell Inc." -> dell, "Hewlett-Packard" -> hewlett-packard)
  model  = slug of product_name (Lenovo: product_version, e.g. "ThinkPad T420" -> thinkpad-t420)

Safety: kernel parameters from research are never applied automatically: they are recorded as
kernel_params_suggested= (shown by `phoenix platform`). Only hand-verified profiles set kernel_params=.
Hand-written profiles (files without the generated marker) are never overwritten.

  gen-profiles.py [--check]      (--check: report only, write nothing)
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARK = "# generated by build/gen-profiles.py"
PARAM = re.compile(r"\b(?:[a-z0-9_]+\.)?[a-z0-9_]+=[A-Za-z0-9_.,:-]+|\b(?:nomodeset|noapic|nolapic|acpi=off|pci=nomsi)\b")

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def as_list(v):
    if v is None: return []
    return v if isinstance(v, list) else [v]

def params(quirks):
    out = []
    for q in as_list(quirks):
        for p in PARAM.findall(q):
            if p not in out: out.append(p)
    return out

def render(e, model):
    conf = e.get("confidence", "low")
    mods = as_list(e.get("platform_modules"))
    lines = [MARK + " from research/ (edit the research JSON, not this file)",
             f"# {as_list(e.get('dmi_vendor'))[0]} {model} ({e.get('years', '?')}): {e.get('cpus', '?')}",
             f"# GPU: {e.get('gpu', '?')}",
             f"# Firmware: {e.get('firmware', '?')}   VT-x: {e.get('vtx', '?')}   Wi-Fi: {e.get('wifi', '?')}",
             f"# Confidence: {conf}"]
    for s in as_list(e.get("sources"))[:6]:
        lines.append(f"# Source: {s}")
    tp = e.get("touchpad", "unknown")
    if tp and tp != "unknown": lines.append(f"touchpad={tp}")
    ps = params(e.get("linux_quirks"))
    if ps:
        lines.append("kernel_params_suggested=" + " ".join(ps))   # never applied automatically
    if mods: lines.append("modules=" + " ".join(mods))
    for m, o in (e.get("module_options") or {}).items():
        if o: lines.append(f"opt_{m.replace('-', '_')}={o}")
    lines.append("cpu_profile=balanced")
    lines.append("fan_mode=bios")
    for k in ("cpu_gen", "gpu_gen", "firmware", "vtx", "chassis", "fan_control", "confidence"):
        if e.get(k): lines.append(f"info_{k}={e[k]}")
    notes = "; ".join([*as_list(e.get("linux_quirks")), e.get("notes", "")]).strip("; ").replace("\n", " ")
    if notes: lines.append("notes=" + notes[:600])
    return "\n".join(lines) + "\n"

def main():
    check = "--check" in sys.argv
    written = skipped = 0
    seen = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "research", "*.json"))):
        for e in json.load(open(f)):
            vendors = as_list(e.get("dmi_vendor"))
            models = [e.get("dmi_model")] + as_list(e.get("aliases"))
            for v in vendors:
                for m in models:
                    if not v or not m or str(m).lower() == "unknown": continue
                    name = slug(m)
                    # Lenovo machine types (4 chars, e.g. 4180 / 20BU): matched via product_name prefix as mt-<type>
                    if slug(v.split()[0]) == "lenovo" and m != e.get("dmi_model") and re.fullmatch(r"[0-9A-Za-z]{4}", str(m)):
                        name = "mt-" + name
                    sub = ["boards"] if e.get("match") == "board" else []   # whitebox motherboards
                    path = os.path.join(ROOT, "profiles", *sub, slug(v.split()[0]), name + ".conf")
                    if path in seen:
                        if seen[path] != "x": print(f"note: {os.path.relpath(path, ROOT)} claimed twice; keeping the first")
                        continue
                    seen[path] = os.path.basename(f)
                    if os.path.exists(path) and MARK not in open(path).read():
                        skipped += 1; continue          # hand-written profile wins
                    if not check:
                        os.makedirs(os.path.dirname(path), exist_ok=True)
                        open(path, "w").write(render(e, m))
                    written += 1
    print(f"{'would write' if check else 'wrote'} {written} profiles, kept {skipped} hand-written")

if __name__ == "__main__":
    main()
